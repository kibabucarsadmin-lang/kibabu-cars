// Collects every translatable English text from the source and writes src/shared/i18n/keys.ts.
// Then checks each language file has exactly one translation per key, with the same {placeholders}.
// Usage: node scripts/i18n-keys.mjs [--check]
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('../src/', import.meta.url).pathname;
const files = [];
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) { if (!/admin|i18n$/.test(f)) walk(p); }
    else if (/\.(ts|html)$/.test(f) && !/\.spec\.ts$|config\.ts$/.test(f)) files.push(p);
  }
};
walk(join(ROOT, 'app')); walk(join(ROOT, 'shared')); walk(join(ROOT, 'server'));
files.push(join(ROOT, 'shared/i18n/extra.ts'));

const STR = String.raw`'((?:[^'\\]|\\.)*)'`;
const patterns = [
  new RegExp(STR + String.raw`\s*\|\s*t\b`, 'g'),
  new RegExp(String.raw`\b(?:tx|t|tr|warn|note|line|i18n\.t)\((?:req,\s*)?` + STR, 'g'),
  new RegExp(String.raw`\?\s*` + STR + String.raw`\s*:\s*` + STR + String.raw`\s*\)\s*\|\s*t\b`, 'g'),
];
const keys = new Set();
const unq = (s) => s.replace(/\\(.)/g, '$1');
for (const f of files) {
  const src = readFileSync(f, 'utf8');
  for (const re of patterns) for (const m of src.matchAll(re)) for (const g of m.slice(1)) if (g && /[A-Za-z]/.test(g)) keys.add(unq(g));
}
const list = [...keys].sort((a, b) => a.localeCompare(b));
const check = process.argv.includes('--check');
const out = `/** Every translatable English text, sorted. Generated by scripts/i18n-keys.mjs – do not edit by hand. */\nexport const KEYS: readonly string[] = ${JSON.stringify(list, null, 1).replace(/\n /g, '\n  ')};\n`;
if (!check) writeFileSync(join(ROOT, 'shared/i18n/keys.ts'), out);
console.log(`${list.length} keys`);

// ---- check translations: every key translated, same {placeholders}, numbers and $ amounts ----
const sig = (s) => [...(s.match(/\{\w+\}/g) ?? []), ...(s.match(/\$?\d+(?:[.,]\d+)?%?/g) ?? []).map((x) => x.replace(',', '.'))].sort().join(' ');
let bad = 0;
for (const lang of ['it', 'ru', 'es', 'de']) {
  const src = readFileSync(join(ROOT, `shared/i18n/${lang}.ts`), 'utf8');
  const dict = new Function(`return ${src.slice(src.indexOf('= {') + 2, src.lastIndexOf('}') + 1)}`)();
  for (const k of list) {
    const v = dict[k];
    if (!v?.trim()) { console.log(`${lang} missing: ${JSON.stringify(k)}`); bad++; }
    else if (sig(k) !== sig(v)) { console.log(`${lang} mismatch:\n   ${k}\n   ${v}`); bad++; }
  }
  for (const k of Object.keys(dict)) if (!keys.has(k)) console.log(`${lang} unused (can be removed): ${JSON.stringify(k)}`);
}
if (bad) { console.log(`${bad} problem(s)`); process.exitCode = 1; } else console.log('translations OK');
